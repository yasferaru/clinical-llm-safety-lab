#!/usr/bin/env python3
"""Generate the README results section from a run's summary files (no number is typed by hand).

    python scripts/readme_results.py results/<run_dir>            # print the section
    python scripts/readme_results.py results/<run_dir> --write    # replace it in README.md between the markers

Reads, from the run directory: meta/manifest.json, report/02_models.csv, report/10_corrected_critical_pass.csv,
category_summary.csv and worst_clusters.csv. Every number and interval is copied verbatim from those files,
including the name of the interval method as the summary code wrote it.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
START, END = (
    "<!-- results:start (generated by scripts/readme_results.py; do not edit by hand) -->",
    "<!-- results:end -->",
)


def table(df: pd.DataFrame, cols: list[str], names: list[str]) -> list[str]:
    """Markdown table of the given columns, cells copied as strings."""
    out = ["| " + " | ".join(names) + " |", "|" + "---|" * len(names)]
    for _, r in df.iterrows():
        out.append("| " + " | ".join(str(r[c]) for c in cols) + " |")
    return out


def section(run_dir: Path) -> str:
    """The generated markdown for one run directory."""
    rel = run_dir.resolve().relative_to(ROOT)
    m = json.loads((run_dir / "meta" / "manifest.json").read_text())
    models = pd.read_csv(run_dir / "report" / "02_models.csv")
    corr = pd.read_csv(run_dir / "report" / "10_corrected_critical_pass.csv")
    cat = pd.read_csv(run_dir / "category_summary.csv").fillna("")
    worst = pd.read_csv(run_dir / "worst_clusters.csv")
    date = m["time_utc"][:10]
    reported = ", ".join(f"`{v}`" for v in m["model_versions_reported"])
    out = [
        START,
        "",
        f"### {m['model']}: {int(models['n_cases'].sum())} cases, run {date}",
        "",
        f"Source files: [`{rel}/report/report.md`]({rel}/report/report.md), "
        f"[`{rel}/category_summary.md`]({rel}/category_summary.md), [`{rel}/RUN_NOTES.md`]({rel}/RUN_NOTES.md).",
        "",
        "| Setting | Value |",
        "|---|---|",
        f"| Model under test | `{m['model']}` (provider reported: {reported}) |",
        f"| Judge | `{m['judge']}`, judge prompt sha256 `{m['judge_prompt_sha256'][:12]}…`, judge temperature "
        f"{m['judge_temperature']} |",
        f"| Epochs / temperature / seed | {m['epochs']} / {m['temperature']} / {m['seed']} |",
        f"| Date (UTC) / Inspect / commit | {date} / {m['inspect_ai']} / `{m['git_commit'][:7]}` (cases.jsonl sha256 "
        f"`{m['cases_jsonl_sha256'][:12]}…`) |",
        "",
    ]
    if not corr["validated"].astype(bool).all():
        out += [
            "> **Judge not validated.** No human calibration labels exist, so every rate below is a raw LLM-judge "
            "rate (`report/10_corrected_critical_pass.csv`: validated = False).",
            "",
        ]
    out += [
        "**Overall** (from `report/02_models.csv`; rubric_score interval: cluster-robust normal CI with the scenario "
        "as the cluster; critical_pass interval: Clopper-Pearson over cases):",
        "",
    ]
    out += table(
        models,
        ["model", "n_cases", "n_clusters", "epochs_per_case", "rubric_score", "critical_pass_all_epochs"],
        ["Model", "Cases", "Scenarios (clusters)", "Epochs", "Mean rubric_score", "critical_pass"],
    )
    out += ["", "**Per category** (from `category_summary.csv`):", ""]
    out += table(
        cat[cat["section"] == "per category"],
        ["category", "cases", "scenarios", "value", "mean_rubric_score"],
        ["Category", "Cases", "Scenarios", "critical_pass", "Mean rubric_score"],
    )
    out += ["", "**Requested outcomes** (from `category_summary.csv`):", ""]
    out += table(cat[cat["section"] == "outcome"], ["category", "measure", "value"], ["Category", "Measure", "Value"])
    out += [
        "",
        "**How critical_pass failures split** (unsafe content = a critical `must_not` line was triggered; "
        "omission only = only a critical `must` line was missed):",
        "",
    ]
    out += table(
        cat[cat["section"] == "failure type"], ["category", "value"], ["Category", "Unsafe content / omission only"]
    )
    out += ["", "**Pressure effect, paired by scenario** (from `category_summary.csv`):", ""]
    out += table(cat[cat["section"] == "pressure effect"], ["category", "value"], ["Category", "Discordant pairs"])
    out += [
        "",
        "**Worst clusters** (from `worst_clusters.csv`: fewest critical passes, then lowest mean rubric_score):",
        "",
    ]
    out += table(
        worst,
        ["category", "scenario_id", "critical_pass", "mean_rubric"],
        ["Category", "Cluster", "critical_pass", "Mean rubric_score"],
    )
    out += ["", END]
    return "\n".join(out)


def main(argv: list[str]) -> None:
    """CLI (see module docstring)."""
    run_dir = Path(argv[0])
    text = section(run_dir)
    if "--write" in argv:
        readme = ROOT / "README.md"
        r = readme.read_text()
        if START not in r or END not in r:
            raise SystemExit("README.md has no results markers")
        readme.write_text(r[: r.index(START)] + text + r[r.index(END) + len(END) :])
        print(f"README.md results section regenerated from {run_dir}")
    else:
        print(text)


if __name__ == "__main__":
    main(sys.argv[1:])
